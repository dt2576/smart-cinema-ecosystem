-- Internal initiation only. Provider/currency binding and any charge are deferred.
CREATE TABLE payment_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_payment_transactions PRIMARY KEY,
    booking_id bigint NOT NULL CONSTRAINT fk_payment_transactions_booking REFERENCES bookings(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    provider varchar(50),
    internal_reference varchar(100) NOT NULL CONSTRAINT uq_payment_transactions_internal_reference UNIQUE,
    external_reference varchar(255),
    amount numeric(19,4) NOT NULL,
    currency varchar(3),
    status varchar(20) NOT NULL DEFAULT 'INITIATED',
    initiated_at timestamp(6) with time zone NOT NULL,
    completed_at timestamp(6) with time zone,
    provider_metadata jsonb NOT NULL DEFAULT '{}',
    CONSTRAINT uq_payment_transactions_provider_external UNIQUE(provider,external_reference),
    CONSTRAINT chk_payment_transactions_reference CHECK(btrim(internal_reference)<>''),
    CONSTRAINT chk_payment_transactions_amount CHECK(amount>=0 AND amount<1000000000000000),
    CONSTRAINT chk_payment_transactions_time CHECK(isfinite(initiated_at)),
    -- No invented provider/currency, result transition or submission capability.
    CONSTRAINT chk_payment_transactions_initiation_stage CHECK(status='INITIATED' AND completed_at IS NULL
        AND provider IS NULL AND currency IS NULL AND external_reference IS NULL AND provider_metadata='{}'::jsonb)
);
CREATE UNIQUE INDEX uq_payment_transactions_unresolved_booking ON payment_transactions(booking_id)
    WHERE status IN ('INITIATED','PENDING');
CREATE INDEX idx_payment_transactions_booking ON payment_transactions(booking_id,id);
ALTER TABLE bookings DROP CONSTRAINT chk_bookings_pre_payment_stage;
