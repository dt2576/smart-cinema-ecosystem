CREATE FUNCTION app.validate_payment_composition(p_booking bigint) RETURNS void
LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,pg_temp AS $body$
DECLARE b app.bookings%ROWTYPE; p app.promotions%ROWTYPE; v_discount numeric; v_used bigint;
BEGIN
    SELECT * INTO b FROM app.bookings WHERE id=p_booking;
    IF NOT app.booking_composition_eligible(p_booking) THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking unavailable for initiation';
    END IF;
    IF b.seat_amount<>(SELECT coalesce(sum(final_price),0) FROM app.booking_seats WHERE booking_id=b.id)
        OR b.concession_amount<>(SELECT coalesce(sum(total_price),0) FROM app.booking_concessions WHERE booking_id=b.id)
        OR b.subtotal<>b.seat_amount+b.concession_amount OR b.final_amount<>b.subtotal-b.discount THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Inconsistent Booking totals';
    END IF;
    IF b.promotion_id IS NOT NULL THEN
        SELECT * INTO p FROM app.promotions WHERE id=b.promotion_id FOR UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0005',MESSAGE='Promotion unavailable'; END IF;
        SELECT count(*) INTO v_used FROM app.bookings WHERE promotion_id=p.id AND status='PAID';
        v_discount:=app.promotion_discount(p,b.subtotal,v_used);
        IF v_discount<>b.discount OR (p.code,p.discount_type,p.discount_value,p.minimum_order,p.max_discount_amount)
            IS DISTINCT FROM (b.promotion_code_snapshot,b.promotion_type_snapshot,b.promotion_value_snapshot,
                b.promotion_minimum_snapshot,b.promotion_cap_snapshot) THEN
            RAISE EXCEPTION USING ERRCODE='P0006',MESSAGE='Promotion terms changed; review composition';
        END IF;
    END IF;
    IF NOT app.booking_composition_eligible(p_booking) THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking expired during initiation';
    END IF;
END $body$;

CREATE FUNCTION app.guard_payment_transaction() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
BEGIN
    IF current_user<>'smart_cinema_hold_owner' OR TG_OP<>'INSERT' THEN
        RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Immutable initiated Payment';
    END IF;
    PERFORM app.validate_payment_composition(NEW.booking_id);
    IF NOT EXISTS(SELECT 1 FROM app.bookings WHERE id=NEW.booking_id AND payment_started_at IS NULL
        AND final_amount=NEW.amount AND created_at<=NEW.initiated_at AND NEW.initiated_at<expires_at)
        OR NEW.initiated_at>clock_timestamp() THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid Payment origin';
    END IF;
    RETURN NEW;
END $body$;
CREATE TRIGGER trg_payment_transactions_guard BEFORE INSERT OR UPDATE OR DELETE ON app.payment_transactions
    FOR EACH ROW EXECUTE FUNCTION app.guard_payment_transaction();

CREATE FUNCTION app.assert_payment_freeze() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_id bigint; b app.bookings%ROWTYPE; v_count bigint;
BEGIN
    IF TG_TABLE_NAME='bookings' THEN v_id:=coalesce(NEW.id,OLD.id); ELSE v_id:=coalesce(NEW.booking_id,OLD.booking_id); END IF;
    SELECT * INTO b FROM app.bookings WHERE id=v_id;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Missing Payment Booking'; END IF;
    SELECT count(*) INTO v_count FROM app.payment_transactions WHERE booking_id=v_id;
    IF (b.payment_started_at IS NULL AND v_count<>0)
        OR (b.payment_started_at IS NOT NULL AND (v_count<>1 OR NOT EXISTS(
            SELECT 1 FROM app.payment_transactions WHERE booking_id=v_id AND initiated_at=b.payment_started_at AND amount=b.final_amount))) THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Payment attempt and freeze must commit together';
    END IF;
    RETURN NULL;
END $body$;
CREATE CONSTRAINT TRIGGER ct_payment_transactions_freeze AFTER INSERT OR UPDATE OR DELETE ON app.payment_transactions
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION app.assert_payment_freeze();
CREATE CONSTRAINT TRIGGER ct_bookings_payment_freeze AFTER INSERT OR UPDATE OR DELETE ON app.bookings
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION app.assert_payment_freeze();

CREATE FUNCTION app.initiate_payment(p_booking bigint,p_user bigint) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_showtime bigint; b app.bookings%ROWTYPE; v_id bigint; v_now timestamptz;
BEGIN
    SELECT showtime_id INTO v_showtime FROM app.bookings WHERE id=p_booking AND customer_id=p_user;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Booking unavailable'; END IF;
    PERFORM app.lock_hold_context(v_showtime,p_user);
    PERFORM app.lock_booking_resources(v_showtime);
    PERFORM app.expire_booking_aggregates(v_showtime);
    SELECT * INTO b FROM app.bookings WHERE id=p_booking;
    IF b.status<>'PENDING' OR b.expires_at<=clock_timestamp() THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking unavailable for initiation';
    END IF;
    IF b.payment_started_at IS NOT NULL THEN
        -- Recovery only, not a fresh eligibility/charge authorization or a reprice.
        SELECT id INTO v_id FROM app.payment_transactions WHERE booking_id=p_booking AND status='INITIATED';
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Missing unresolved Payment'; END IF;
        RETURN v_id;
    END IF;
    PERFORM app.validate_payment_composition(p_booking);
    v_now:=clock_timestamp();
    INSERT INTO app.payment_transactions(booking_id,internal_reference,amount,initiated_at)
        VALUES(p_booking,'P-'||replace(gen_random_uuid()::text,'-',''),b.final_amount,v_now) RETURNING id INTO v_id;
    UPDATE app.bookings SET payment_started_at=v_now WHERE id=p_booking;
    RETURN v_id;
END $body$;

