CREATE OR REPLACE FUNCTION app.guard_payment_transaction() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
BEGIN
 IF current_user<>'smart_cinema_hold_owner' OR TG_OP='DELETE' THEN
 RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Protected Payment'; END IF;
 IF TG_OP='INSERT' THEN
  IF NEW.status<>'INITIATED' OR NEW.provider IS NOT NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid initial Payment'; END IF;
  IF EXISTS(SELECT 1 FROM app.bookings WHERE id=NEW.booking_id AND payment_started_at IS NULL) THEN
   PERFORM app.validate_payment_composition(NEW.booking_id);
  ELSIF NOT app.payment_settlement_eligible(NEW.booking_id) OR EXISTS(SELECT 1 FROM app.payment_transactions
    WHERE booking_id=NEW.booking_id AND (status NOT IN ('FAILED','CANCELLED') OR reconciliation_required)) THEN
   RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Payment retry unavailable';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM app.bookings WHERE id=NEW.booking_id AND final_amount=NEW.amount
   AND created_at<=NEW.initiated_at AND NEW.initiated_at<expires_at) OR NEW.initiated_at>clock_timestamp() THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid Payment origin'; END IF;
 ELSE
  IF (NEW.id,NEW.booking_id,NEW.internal_reference,NEW.amount,NEW.initiated_at) IS DISTINCT FROM
   (OLD.id,OLD.booking_id,OLD.internal_reference,OLD.amount,OLD.initiated_at)
   OR (OLD.provider IS NOT NULL AND (to_jsonb(NEW)-ARRAY['status','completed_at','external_reference','reconciliation_required','next_query_at'])
     IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status','completed_at','external_reference','reconciliation_required','next_query_at']))
   OR (OLD.external_reference IS NOT NULL AND NEW.external_reference IS DISTINCT FROM OLD.external_reference)
   OR (OLD.status='SUCCESS' AND NEW.status<>'SUCCESS') THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable Payment identity'; END IF;
  IF NEW.status IN ('SUCCESS','FAILED','CANCELLED') AND NOT EXISTS(SELECT 1 FROM app.payment_evidence
    WHERE payment_id=NEW.id AND result=NEW.status) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Payment requires trusted evidence'; END IF;
 END IF;
 RETURN NEW;
END $body$;

