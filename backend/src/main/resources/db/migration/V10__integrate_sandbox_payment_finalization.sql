CREATE FUNCTION app.bind_vnpay_submission(p_payment bigint,p_user bigint,p_merchant text,p_return text,p_ip text,p_order text DEFAULT 'other')
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE b app.bookings%ROWTYPE; p app.payment_transactions%ROWTYPE; v_now timestamptz; v_end timestamptz;
BEGIN
 SELECT b0.* INTO b FROM app.bookings b0 JOIN app.payment_transactions p0 ON p0.booking_id=b0.id WHERE p0.id=p_payment AND b0.customer_id=p_user;
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Payment unavailable'; END IF;
 PERFORM app.lock_hold_context(b.showtime_id,p_user); PERFORM app.lock_booking_resources(b.showtime_id);
 PERFORM id FROM app.promotions WHERE id=b.promotion_id FOR UPDATE;
 SELECT * INTO p FROM app.payment_transactions WHERE id=p_payment FOR UPDATE;
 IF NOT app.payment_settlement_eligible(b.id) OR p.status NOT IN ('INITIATED','PENDING') OR p.reconciliation_required
 OR EXISTS(SELECT 1 FROM app.payment_transactions other WHERE other.booking_id=b.id AND other.id<>p.id
   AND (other.status='SUCCESS' OR other.reconciliation_required)) THEN
  RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Submission unavailable'; END IF;
 IF p.provider IS NOT NULL THEN
  IF p.merchant_code<>p_merchant OR p.return_url<>p_return OR p.provider_expires_at<=clock_timestamp() THEN
   RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Submission binding conflict'; END IF;
  RETURN p.id;
 END IF;
 v_now:=date_trunc('second',clock_timestamp()); v_end:=date_trunc('second',b.expires_at);
 IF p.amount<=0 OR trunc(p.amount)<>p.amount OR p.amount*100>999999999999 OR v_end<=v_now THEN
  RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Unsupported provider amount or deadline'; END IF;
 UPDATE app.payment_transactions SET provider='VNPAY',environment='SANDBOX',currency='VND',merchant_code=p_merchant,
  merchant_reference=replace(internal_reference,'-',''),submitted_amount=amount*100,provider_created_at=v_now,
  provider_expires_at=v_end,return_url=p_return,client_ip=p_ip,status='PENDING',
  provider_metadata=jsonb_build_object('order_type',p_order) WHERE id=p.id;
 RETURN p.id;
END $body$;

CREATE FUNCTION app.record_vnpay_result(p_merchant text,p_reference text,p_amount numeric,p_external text,
 p_source text,p_digest text,p_result text,p_code text,p_status text) RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE p app.payment_transactions%ROWTYPE; b app.bookings%ROWTYPE; v_evidence bigint; v_reason text;
 v_now timestamptz; v_limit bigint; v_used bigint;
BEGIN
 SELECT * INTO p FROM app.payment_transactions WHERE provider='VNPAY' AND environment='SANDBOX'
  AND merchant_code=p_merchant AND merchant_reference=p_reference;
 IF NOT FOUND THEN RETURN '01'; END IF;
 IF p_amount IS DISTINCT FROM p.submitted_amount THEN RETURN '04'; END IF;
 SELECT * INTO b FROM app.bookings WHERE id=p.booking_id;
 PERFORM app.lock_hold_context(b.showtime_id,NULL); PERFORM app.lock_booking_resources(b.showtime_id);
 SELECT usage_limit INTO v_limit FROM app.promotions WHERE id=b.promotion_id FOR UPDATE;
 SELECT * INTO p FROM app.payment_transactions WHERE id=p.id FOR UPDATE;
 SELECT * INTO b FROM app.bookings WHERE id=p.booking_id;
 INSERT INTO app.payment_evidence(payment_id,source,digest,result,response_code,transaction_status,external_reference)
 VALUES(p.id,p_source,p_digest,p_result,p_code,p_status,p_external) ON CONFLICT DO NOTHING RETURNING id INTO v_evidence;
 IF v_evidence IS NULL THEN RETURN '02'; END IF;
 IF (p.external_reference IS NOT NULL AND p_external IS NOT NULL AND p.external_reference<>p_external)
 OR EXISTS(SELECT 1 FROM app.payment_transactions other WHERE other.id<>p.id AND other.provider='VNPAY'
   AND other.environment='SANDBOX' AND other.merchant_code=p_merchant AND other.external_reference=p_external) THEN v_reason:='REFERENCE_CONFLICT';
 ELSIF p_result='RECONCILE' THEN v_reason:='SPECIAL_RESULT';
 ELSIF p.status IN ('FAILED','CANCELLED') AND p_result<>p.status THEN v_reason:='TERMINAL_CORRECTION';
 ELSIF p.status='SUCCESS' AND p_result<>'SUCCESS' THEN v_reason:='CONTRADICTORY_RESULT';
 ELSIF p.reconciliation_required AND p.status<>'SUCCESS' THEN v_reason:='EXISTING_RECONCILIATION';
 ELSIF p_result='SUCCESS' AND p.status<>'SUCCESS' AND EXISTS(SELECT 1 FROM app.payment_transactions other
   WHERE other.booking_id=b.id AND other.id<>p.id AND (other.status='SUCCESS' OR other.reconciliation_required)) THEN
  v_reason:='ADDITIONAL_FINANCIAL_SUCCESS';
 END IF;
 IF v_reason IS NULL OR (p_result='SUCCESS' AND v_reason IN ('TERMINAL_CORRECTION','EXISTING_RECONCILIATION','ADDITIONAL_FINANCIAL_SUCCESS')) THEN
  UPDATE app.payment_transactions SET status=CASE WHEN p.status='SUCCESS' THEN 'SUCCESS' ELSE p_result END,
   completed_at=CASE WHEN p_result IN ('SUCCESS','FAILED','CANCELLED') THEN coalesce(completed_at,clock_timestamp()) ELSE completed_at END,
   external_reference=coalesce(external_reference,p_external) WHERE id=p.id;
 END IF;
 IF p_result='SUCCESS' AND v_reason IS NULL AND b.status<>'PAID' THEN
  SELECT count(*) INTO v_used FROM app.bookings WHERE promotion_id=b.promotion_id AND status='PAID';
  IF NOT app.payment_settlement_eligible(b.id) THEN v_reason:='FULFILLMENT_UNAVAILABLE';
  ELSIF v_limit IS NOT NULL AND v_used>=v_limit THEN v_reason:='PROMOTION_EXHAUSTED';
  ELSE
   v_now:=clock_timestamp();
   UPDATE app.bookings SET status='PAID',paid_at=v_now,booking_qr_token=replace(gen_random_uuid()::text,'-','')||replace(gen_random_uuid()::text,'-','') WHERE id=b.id;
   UPDATE app.booking_seats SET sold_at=v_now WHERE booking_id=b.id;
   UPDATE app.seat_holds SET status='CONSUMED' WHERE booking_id=b.id;
   INSERT INTO app.tickets(booking_seat_id,ticket_code,status,issued_at)
    SELECT id,'T-'||replace(gen_random_uuid()::text,'-',''),'VALID',v_now FROM app.booking_seats WHERE booking_id=b.id;
   INSERT INTO app.audit_records(action,resource_type,resource_id,metadata)
    VALUES('SALE_FINALIZED','BOOKING',b.id,jsonb_build_object('system_actor','VNPAY','payment_id',p.id::text,'evidence_id',v_evidence::text));
  END IF;
 ELSIF p_result='SUCCESS' AND b.status='PAID' AND p.status<>'SUCCESS' THEN v_reason:='ADDITIONAL_FINANCIAL_SUCCESS';
 END IF;
 IF v_reason IS NOT NULL THEN
  UPDATE app.payment_transactions SET reconciliation_required=true WHERE id=p.id;
  INSERT INTO app.payment_reconciliations(payment_id,reason,evidence_id) VALUES(p.id,v_reason,v_evidence)
   ON CONFLICT(payment_id,reason) DO UPDATE SET last_observed_at=clock_timestamp(),resolved_at=NULL,resolved_by_user_id=NULL,resolution_note=NULL;
 END IF;
 PERFORM app.expire_booking_aggregates(b.showtime_id);
 INSERT INTO app.audit_records(action,resource_type,resource_id,metadata) VALUES('PAYMENT_OBSERVED','PAYMENT',p.id,
  jsonb_build_object('system_actor','VNPAY','evidence_id',v_evidence::text,'result',p_result,'reason',v_reason));
 RETURN '00';
END $body$;
-- Scheduling-only claim: holds no parent/domain locks and commits before network I/O.
CREATE FUNCTION app.claim_vnpay_queries(p_merchant text,p_delay interval,p_horizon interval)
RETURNS SETOF app.payment_transactions LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE p app.payment_transactions%ROWTYPE;
BEGIN
 IF p_delay<=interval '0 seconds' OR p_horizon<=interval '0 seconds' THEN
  RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invalid query schedule'; END IF;
 FOR p IN SELECT * FROM app.payment_transactions WHERE merchant_code=p_merchant AND environment='SANDBOX'
  AND status='PENDING' AND NOT reconciliation_required AND coalesce(next_query_at,provider_created_at)<=clock_timestamp()
  ORDER BY id LIMIT 20 FOR UPDATE SKIP LOCKED LOOP
  IF p.provider_created_at+p_horizon<=clock_timestamp() THEN
   UPDATE app.payment_transactions SET reconciliation_required=true WHERE id=p.id;
   INSERT INTO app.payment_reconciliations(payment_id,reason) VALUES(p.id,'QUERY_HORIZON') ON CONFLICT DO NOTHING;
   INSERT INTO app.audit_records(action,resource_type,resource_id,metadata) VALUES('QUERY_ESCALATED','PAYMENT',p.id,
    jsonb_build_object('system_actor','VNPAY_QUERY'));
  ELSE
   UPDATE app.payment_transactions SET next_query_at=clock_timestamp()+p_delay WHERE id=p.id;
   RETURN NEXT p;
  END IF;
 END LOOP;
END $body$;
