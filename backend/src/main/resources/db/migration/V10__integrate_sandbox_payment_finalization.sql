CREATE FUNCTION app.assert_paid_aggregate() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_booking bigint; b app.bookings%ROWTYPE;
BEGIN
 IF TG_TABLE_NAME='tickets' THEN SELECT booking_id INTO v_booking FROM app.booking_seats WHERE id=coalesce(NEW.booking_seat_id,OLD.booking_seat_id);
 ELSIF TG_TABLE_NAME='bookings' THEN v_booking:=coalesce(NEW.id,OLD.id);
 ELSE v_booking:=coalesce(NEW.booking_id,OLD.booking_id); END IF;
 IF v_booking IS NULL THEN RETURN NULL; END IF;
 SELECT * INTO b FROM app.bookings WHERE id=v_booking;
 IF b.status='PAID' THEN
  IF NOT EXISTS(SELECT 1 FROM app.payment_transactions WHERE booking_id=b.id AND status='SUCCESS' AND amount=b.final_amount)
   OR NOT EXISTS(SELECT 1 FROM app.audit_records WHERE resource_type='BOOKING' AND resource_id=b.id AND action='SALE_FINALIZED')
   OR EXISTS(SELECT 1 FROM app.booking_seats bs LEFT JOIN app.tickets t ON t.booking_seat_id=bs.id
     LEFT JOIN app.seat_holds h ON h.booking_id=bs.booking_id AND h.seat_id=bs.seat_id
     WHERE bs.booking_id=b.id AND (bs.sold_at IS DISTINCT FROM b.paid_at OR t.id IS NULL
       OR t.issued_at IS DISTINCT FROM b.paid_at OR h.status IS DISTINCT FROM 'CONSUMED')) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Incomplete paid aggregate'; END IF;
 ELSE
  IF EXISTS(SELECT 1 FROM app.booking_seats bs LEFT JOIN app.tickets t ON t.booking_seat_id=bs.id
     WHERE bs.booking_id=b.id AND (bs.sold_at IS NOT NULL OR t.id IS NOT NULL))
   OR EXISTS(SELECT 1 FROM app.seat_holds WHERE booking_id=b.id AND status='CONSUMED') THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Unpaid entitlement'; END IF;
 END IF;
 RETURN NULL;
END $body$;
