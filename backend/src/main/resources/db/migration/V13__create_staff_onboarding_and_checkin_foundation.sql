CREATE FUNCTION app.staff_lock_admin(p_actor bigint,p_target bigint) RETURNS void
LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $b$
BEGIN
 PERFORM id FROM app.users WHERE id IN (p_actor,p_target) ORDER BY id FOR UPDATE;
 IF NOT EXISTS(SELECT 1 FROM app.users WHERE id=p_actor AND role='ADMIN' AND status='ACTIVE') THEN RAISE EXCEPTION USING ERRCODE='P0004',MESSAGE='Admin unavailable'; END IF;
