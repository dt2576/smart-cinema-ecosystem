CREATE FUNCTION app.assert_ticket_checkin() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $b$
DECLARE v_id bigint; t app.tickets%ROWTYPE; v_meta jsonb;
BEGIN
 IF TG_TABLE_NAME='audit_records' THEN
  IF NEW.resource_type<>'TICKET' OR NEW.action<>'TICKET_CHECKED_IN' THEN RETURN NULL; END IF; v_id:=NEW.resource_id;
 ELSE v_id:=NEW.id; END IF;
 SELECT * INTO t FROM app.tickets WHERE id=v_id;
 SELECT jsonb_build_object('booking_id',bs.booking_id::text,'cinema_id',h.cinema_id::text,'showtime_id',bs.showtime_id::text) INTO v_meta FROM app.booking_seats bs JOIN app.showtimes s ON s.id=bs.showtime_id JOIN app.halls h ON h.id=s.hall_id WHERE bs.id=t.booking_seat_id;
 IF t.status IS DISTINCT FROM 'CHECKED_IN' OR NOT EXISTS(SELECT 1 FROM app.audit_records WHERE resource_type='TICKET' AND resource_id=v_id AND action='TICKET_CHECKED_IN'
 AND actor_user_id=t.checked_in_by_user_id AND occurred_at=t.checked_in_at AND metadata=v_meta) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Incomplete Ticket Check-in audit'; END IF;
 RETURN NULL;
END $b$;
CREATE CONSTRAINT TRIGGER ct_ticket_checkin AFTER UPDATE ON app.tickets DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN(NEW.status='CHECKED_IN') EXECUTE FUNCTION app.assert_ticket_checkin();
CREATE CONSTRAINT TRIGGER ct_ticket_checkin_audit AFTER INSERT ON app.audit_records DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION app.assert_ticket_checkin();
