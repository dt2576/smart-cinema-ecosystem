CREATE FUNCTION app.check_in_tickets(p_actor bigint,p_booking bigint,p_cinema bigint,p_tickets bigint[]) RETURNS SETOF app.tickets
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp SET lock_timeout='2s' AS $b$
DECLARE v_showtime bigint; v_now timestamptz; v_count integer; v_start timestamptz; v_state text; v_cstate text; v_hstate text; t app.tickets%ROWTYPE;
BEGIN
 PERFORM id FROM app.users WHERE id=p_actor AND role='STAFF' AND status='ACTIVE' FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0004',MESSAGE='Staff unavailable'; END IF;
 SELECT showtime_id INTO v_showtime FROM app.bookings WHERE id=p_booking;
 IF v_showtime IS NULL THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Booking unavailable'; END IF;
 PERFORM app.lock_staff_admission_resources(v_showtime);
 SELECT s.start_time,s.status,c.status,h.status INTO v_start,v_state,v_cstate,v_hstate FROM app.showtimes s JOIN app.halls h ON h.id=s.hall_id JOIN app.cinemas c ON c.id=h.cinema_id WHERE s.id=v_showtime AND c.id=p_cinema;
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Booking unavailable'; END IF;
 v_now:=clock_timestamp();
 IF NOT EXISTS(SELECT 1 FROM app.cinema_assignments WHERE user_id=p_actor AND cinema_id=p_cinema AND assignment_type='STAFF' AND status='ACTIVE' AND effective_at<=v_now) THEN
 RAISE EXCEPTION USING ERRCODE='P0004',MESSAGE='Staff scope unavailable'; END IF;
 IF NOT app.staff_admission_at(v_start,v_state,v_cstate,v_hstate,v_now) OR NOT EXISTS(SELECT 1 FROM app.bookings WHERE id=p_booking AND status='PAID' AND paid_at IS NOT NULL AND booking_qr_token IS NOT NULL)
 OR NOT EXISTS(SELECT 1 FROM app.booking_seats WHERE booking_id=p_booking)
 OR EXISTS(SELECT 1 FROM app.booking_seats bs JOIN app.bookings b ON b.id=bs.booking_id LEFT JOIN app.tickets ticket ON ticket.booking_seat_id=bs.id
 WHERE bs.booking_id=p_booking AND (ticket.id IS NULL OR ticket.issued_at IS DISTINCT FROM b.paid_at OR bs.sold_at IS DISTINCT FROM b.paid_at)) THEN
 RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Admission unavailable'; END IF;
 IF p_tickets IS NULL OR cardinality(p_tickets)=0 OR array_ndims(p_tickets)<>1 OR EXISTS(SELECT 1 FROM unnest(p_tickets) id WHERE id IS NULL OR id<=0)
 OR cardinality(p_tickets)<>(SELECT count(DISTINCT id) FROM unnest(p_tickets) id) THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invalid Ticket selection'; END IF;
 PERFORM ticket.id FROM app.tickets ticket JOIN app.booking_seats bs ON bs.id=ticket.booking_seat_id WHERE bs.booking_id=p_booking AND ticket.id=ANY(p_tickets) ORDER BY ticket.id FOR UPDATE OF ticket;
 SELECT count(*) INTO v_count FROM app.tickets ticket JOIN app.booking_seats bs ON bs.id=ticket.booking_seat_id WHERE bs.booking_id=p_booking AND ticket.id=ANY(p_tickets);
 IF v_count<>cardinality(p_tickets) THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Ticket selection unavailable'; END IF;
 SELECT count(*) INTO v_count FROM app.tickets ticket JOIN app.booking_seats bs ON bs.id=ticket.booking_seat_id WHERE bs.booking_id=p_booking AND ticket.id=ANY(p_tickets) AND ticket.status='VALID';
 IF v_count<>cardinality(p_tickets) THEN RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Ticket selection unavailable'; END IF;
 -- Capture and recheck after Ticket waits too; caller cannot backdate admission.
 v_now:=clock_timestamp();
 IF NOT app.staff_admission_at(v_start,v_state,v_cstate,v_hstate,v_now) THEN RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Admission unavailable'; END IF;
 FOR t IN UPDATE app.tickets SET status='CHECKED_IN',checked_in_at=v_now,checked_in_by_user_id=p_actor WHERE id=ANY(p_tickets) RETURNING * LOOP
  INSERT INTO app.audit_records(actor_user_id,action,resource_type,resource_id,occurred_at,metadata) VALUES(p_actor,'TICKET_CHECKED_IN','TICKET',t.id,v_now,jsonb_build_object('booking_id',p_booking::text,'cinema_id',p_cinema::text,'showtime_id',v_showtime::text));
  RETURN NEXT t;
 END LOOP;
END $b$;
