CREATE FUNCTION app.staff_rate_limit(p_scope text,p_key text) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $b$
DECLARE v_limit integer; v_span interval; v_now timestamptz:=clock_timestamp(); v_hits integer;
BEGIN
 IF p_scope='REDEMPTION' THEN v_limit:=10;v_span:=interval '1 minute'; ELSIF p_scope='REISSUE' THEN v_limit:=3;v_span:=interval '1 hour'; ELSE RETURN false; END IF;
 IF p_key IS NULL OR p_key !~ '^[0-9a-f]{64}$' THEN RETURN false; END IF;
 DELETE FROM app.staff_rate_limits WHERE window_at<v_now-interval '7 days';
 INSERT INTO app.staff_rate_limits(scope,key_digest,window_at,hits) VALUES(p_scope,p_key,v_now,1)
 ON CONFLICT(scope,key_digest) DO UPDATE SET hits=CASE WHEN app.staff_rate_limits.window_at+v_span<=v_now THEN 1 ELSE least(app.staff_rate_limits.hits+1,v_limit+1) END,
 window_at=CASE WHEN app.staff_rate_limits.window_at+v_span<=v_now THEN v_now ELSE app.staff_rate_limits.window_at END RETURNING hits INTO v_hits;
 RETURN v_hits<=v_limit;
END $b$;
CREATE FUNCTION app.staff_claim_delivery(p_max integer,p_lease interval) RETURNS SETOF app.staff_invitation_deliveries
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $b$
DECLARE d app.staff_invitation_deliveries%ROWTYPE;
BEGIN
 IF p_max<1 OR p_max>10 OR p_lease<interval '1 minute' OR p_lease>interval '30 minutes' THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invalid delivery limits'; END IF;
 UPDATE app.staff_invitation_deliveries pending SET status='EXPIRED',key_id=NULL,nonce=NULL,ciphertext=NULL,lease_id=NULL,lease_until=NULL,completed_at=clock_timestamp()
 FROM app.staff_invitations i WHERE i.id=pending.invitation_id AND i.expires_at<=clock_timestamp() AND pending.status IN ('QUEUED','LEASED');
 SELECT * INTO d FROM app.staff_invitation_deliveries WHERE (status='QUEUED' AND next_attempt_at<=clock_timestamp()) OR (status='LEASED' AND lease_until<=clock_timestamp()) ORDER BY id LIMIT 1 FOR UPDATE SKIP LOCKED;
 IF NOT FOUND THEN RETURN; END IF;
 IF NOT EXISTS(SELECT 1 FROM app.staff_invitations i JOIN app.staff_onboarding o ON o.user_id=i.user_id JOIN app.users u ON u.id=i.user_id
 WHERE i.id=d.invitation_id AND i.consumed_at IS NULL AND i.revoked_at IS NULL AND i.expires_at>clock_timestamp() AND o.password_set_at IS NULL AND u.role='STAFF' AND u.status='BLOCKED') THEN
  UPDATE app.staff_invitation_deliveries SET status='EXPIRED',key_id=NULL,nonce=NULL,ciphertext=NULL,lease_id=NULL,lease_until=NULL,completed_at=clock_timestamp() WHERE id=d.id; RETURN;
 END IF;
 IF d.attempts>=p_max THEN
  UPDATE app.staff_invitation_deliveries SET status='FAILED',key_id=NULL,nonce=NULL,ciphertext=NULL,lease_id=NULL,lease_until=NULL,completed_at=clock_timestamp() WHERE id=d.id; RETURN;
 END IF;
 UPDATE app.staff_invitation_deliveries SET status='LEASED',attempts=attempts+1,lease_id=gen_random_uuid(),lease_until=clock_timestamp()+p_lease WHERE id=d.id RETURNING * INTO d;
 RETURN NEXT d;
END $b$;
CREATE FUNCTION app.staff_finish_delivery(p_id bigint,p_lease uuid,p_success boolean,p_max integer,p_delay interval) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $b$
DECLARE d app.staff_invitation_deliveries%ROWTYPE; v_open boolean;
BEGIN
 SELECT * INTO d FROM app.staff_invitation_deliveries WHERE id=p_id AND status='LEASED' AND lease_id=p_lease FOR UPDATE;
 IF NOT FOUND THEN RETURN; END IF;
 SELECT i.consumed_at IS NULL AND i.revoked_at IS NULL AND i.expires_at>clock_timestamp() INTO v_open FROM app.staff_invitations i WHERE i.id=d.invitation_id;
 IF v_open AND NOT p_success AND d.attempts<p_max THEN
  UPDATE app.staff_invitation_deliveries SET status='QUEUED',lease_id=NULL,lease_until=NULL,next_attempt_at=clock_timestamp()+p_delay WHERE id=d.id;
 ELSE
  UPDATE app.staff_invitation_deliveries SET status=CASE WHEN NOT v_open THEN 'EXPIRED' WHEN p_success THEN 'SENT' ELSE 'FAILED' END,
   key_id=NULL,nonce=NULL,ciphertext=NULL,lease_id=NULL,lease_until=NULL,completed_at=clock_timestamp() WHERE id=d.id;
 END IF;
END $b$;

