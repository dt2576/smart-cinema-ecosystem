END $b$;
CREATE FUNCTION app.staff_guard_record() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $b$
BEGIN
 IF TG_OP='DELETE' AND TG_TABLE_NAME='staff_rate_limits' AND current_user='smart_cinema_staff_owner' THEN
  IF OLD.window_at<clock_timestamp()-interval '7 days' THEN RETURN OLD; END IF;
 END IF;
 IF current_user<>'smart_cinema_staff_owner' OR TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Protected Staff record'; END IF;
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='staff_invitations' THEN
  IF (NEW.id,NEW.user_id,NEW.purpose,NEW.token_digest,NEW.issued_at,NEW.expires_at) IS DISTINCT FROM (OLD.id,OLD.user_id,OLD.purpose,OLD.token_digest,OLD.issued_at,OLD.expires_at) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable invitation';
  END IF;
  IF OLD.consumed_at IS NOT NULL OR OLD.revoked_at IS NOT NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Terminal invitation'; END IF;
 END IF;
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='staff_onboarding' THEN
  IF (NEW.user_id,NEW.created_by_user_id,NEW.created_at) IS DISTINCT FROM (OLD.user_id,OLD.created_by_user_id,OLD.created_at)
   OR OLD.password_set_at IS NOT NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable onboarding'; END IF;
 END IF;
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='cinema_assignments' THEN
  IF (NEW.id,NEW.user_id,NEW.cinema_id,NEW.assignment_type,NEW.effective_at) IS DISTINCT FROM (OLD.id,OLD.user_id,OLD.cinema_id,OLD.assignment_type,OLD.effective_at) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable assignment identity'; END IF;
 END IF;
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='staff_invitation_deliveries' THEN
  IF (NEW.id,NEW.invitation_id) IS DISTINCT FROM (OLD.id,OLD.invitation_id) OR NEW.attempts<OLD.attempts THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable delivery identity'; END IF;
  IF NEW.status IN ('QUEUED','LEASED') AND (NEW.key_id,NEW.nonce,NEW.ciphertext) IS DISTINCT FROM (OLD.key_id,OLD.nonce,OLD.ciphertext) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable delivery payload'; END IF;
 END IF;
 RETURN NEW;
END $b$;
