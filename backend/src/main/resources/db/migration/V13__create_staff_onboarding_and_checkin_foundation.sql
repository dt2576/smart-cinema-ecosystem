CREATE FUNCTION app.staff_set_password(p_digest text,p_hash text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $b$
DECLARE v_user bigint; i app.staff_invitations%ROWTYPE; v_now timestamptz;
BEGIN
 SELECT user_id INTO v_user FROM app.staff_invitations WHERE token_digest=p_digest;
 IF v_user IS NULL THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invitation unavailable'; END IF;
 PERFORM id FROM app.users WHERE id=v_user FOR UPDATE;
 SELECT * INTO i FROM app.staff_invitations WHERE token_digest=p_digest FOR UPDATE;
 v_now:=clock_timestamp();
 IF i.purpose<>'STAFF_PASSWORD_SETUP' OR i.consumed_at IS NOT NULL OR i.revoked_at IS NOT NULL OR NOT app.staff_invitation_at(i.issued_at,i.expires_at,v_now)
 OR NOT EXISTS(SELECT 1 FROM app.users u JOIN app.staff_onboarding o ON o.user_id=u.id WHERE u.id=v_user AND u.role='STAFF' AND u.status='BLOCKED' AND o.password_set_at IS NULL)
 OR p_hash IS NULL OR p_hash !~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$' THEN RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invitation unavailable'; END IF;
 UPDATE app.users SET password_hash=p_hash,updated_at=v_now WHERE id=v_user;
 UPDATE app.staff_onboarding SET password_set_at=v_now WHERE user_id=v_user;
 UPDATE app.staff_invitations SET consumed_at=v_now WHERE id=i.id;
 UPDATE app.staff_invitation_deliveries SET status='REVOKED',key_id=NULL,nonce=NULL,ciphertext=NULL,lease_id=NULL,lease_until=NULL,completed_at=v_now WHERE invitation_id=i.id AND status IN ('QUEUED','LEASED');
 INSERT INTO app.audit_records(actor_user_id,action,resource_type,resource_id,occurred_at,metadata) VALUES(v_user,'STAFF_PASSWORD_SET','USER',v_user,v_now,'{}');
END $b$;
