CREATE FUNCTION app.assert_booking() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_id bigint; b app.bookings%ROWTYPE;
BEGIN
    IF TG_TABLE_NAME='bookings' THEN v_id:=coalesce(NEW.id,OLD.id); ELSE v_id:=coalesce(NEW.booking_id,OLD.booking_id); END IF;
    IF v_id IS NULL THEN RETURN NULL; END IF;
    SELECT * INTO b FROM app.bookings WHERE id=v_id;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Missing Booking aggregate'; END IF;
    IF NOT EXISTS(SELECT 1 FROM app.booking_seats WHERE booking_id=v_id)
        OR b.seat_amount<>(SELECT coalesce(sum(final_price),0) FROM app.booking_seats WHERE booking_id=v_id)
        OR b.expires_at>(SELECT booking_cut_off FROM app.showtimes WHERE id=b.showtime_id)
        OR EXISTS(SELECT 1 FROM app.booking_seats bs LEFT JOIN app.seat_holds h
            ON h.booking_id=bs.booking_id AND h.seat_id=bs.seat_id AND h.showtime_id=bs.showtime_id
            WHERE bs.booking_id=v_id AND (h.id IS NULL OR h.user_id<>b.customer_id OR b.expires_at>h.expires_at
                OR (b.status='PENDING' AND h.status<>'ACTIVE')
                OR (b.status IN ('EXPIRED','CANCELLED') AND h.status NOT IN ('EXPIRED','RELEASED'))
                OR bs.sold_at IS NOT NULL)) THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Incomplete Booking aggregate';
    END IF;
    RETURN NULL;
END $body$;
