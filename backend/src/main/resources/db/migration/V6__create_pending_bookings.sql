        AND NEW.final_price=NEW.unit_price_snapshot) THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid Booking Seat origin or snapshot';
    END IF;
    RETURN NEW;
END $body$;
