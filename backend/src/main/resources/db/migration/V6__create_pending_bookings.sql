CREATE TABLE bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_bookings PRIMARY KEY,
    booking_code varchar(40) NOT NULL CONSTRAINT uq_bookings_code UNIQUE,
    booking_qr_token varchar(128) CONSTRAINT uq_bookings_qr UNIQUE,
    customer_id bigint NOT NULL CONSTRAINT fk_bookings_customer REFERENCES users(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    showtime_id bigint NOT NULL CONSTRAINT fk_bookings_showtime REFERENCES showtimes(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    promotion_id bigint,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    seat_amount numeric(19,4) NOT NULL,
    concession_amount numeric(19,4) NOT NULL,
    subtotal numeric(19,4) NOT NULL,
    discount numeric(19,4) NOT NULL,
    final_amount numeric(19,4) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamp(6) with time zone NOT NULL,
    payment_started_at timestamp(6) with time zone,
    paid_at timestamp(6) with time zone,
    CONSTRAINT uq_bookings_id_showtime UNIQUE(id,showtime_id),
    CONSTRAINT uq_bookings_id_showtime_customer UNIQUE(id,showtime_id,customer_id),
    CONSTRAINT chk_bookings_code CHECK(btrim(booking_code)<>''),
    CONSTRAINT chk_bookings_qr CHECK(booking_qr_token IS NULL OR btrim(booking_qr_token)<>''),
    CONSTRAINT chk_bookings_status CHECK(status IN ('PENDING','PAID','EXPIRED','CANCELLED')),
    CONSTRAINT chk_bookings_times CHECK(isfinite(created_at) AND isfinite(expires_at) AND expires_at>created_at
        AND (payment_started_at IS NULL OR (isfinite(payment_started_at) AND payment_started_at>=created_at AND payment_started_at<expires_at))
        AND (paid_at IS NULL OR (isfinite(paid_at) AND paid_at>=payment_started_at AND paid_at<expires_at))),
    CONSTRAINT chk_bookings_money CHECK(seat_amount>=0 AND seat_amount<1000000000000000
        AND concession_amount>=0 AND concession_amount<1000000000000000
        AND subtotal>=0 AND subtotal<1000000000000000 AND discount>=0 AND discount<1000000000000000
        AND final_amount>=0 AND final_amount<1000000000000000),
    CONSTRAINT chk_bookings_totals CHECK(subtotal=seat_amount+concession_amount AND discount<=subtotal AND final_amount=subtotal-discount),
    CONSTRAINT chk_bookings_promotion CHECK(promotion_id IS NOT NULL OR discount=0),
    CONSTRAINT chk_bookings_paid CHECK((status='PAID' AND paid_at IS NOT NULL AND payment_started_at IS NOT NULL AND booking_qr_token IS NOT NULL)
        OR (status<>'PAID' AND paid_at IS NULL AND booking_qr_token IS NULL)),
    CONSTRAINT chk_bookings_pre_payment_stage CHECK(status<>'PAID' AND payment_started_at IS NULL
        AND promotion_id IS NULL AND concession_amount=0 AND discount=0)
);
