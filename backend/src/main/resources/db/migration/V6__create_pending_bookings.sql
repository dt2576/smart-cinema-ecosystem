-- Caller owns the Showtime gate. Lock the full resource set before any Booking/Hold mutation.
-- Conservative MVP scope: all pairs for this Showtime, avoiding aggregate expansion inversions.
CREATE FUNCTION app.lock_booking_resources(p_showtime bigint) RETURNS void LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
BEGIN
    PERFORM seat.id FROM app.seats seat JOIN app.showtimes s ON s.hall_id=seat.hall_id WHERE s.id=p_showtime ORDER BY seat.id FOR SHARE OF seat;
    PERFORM id FROM app.showtime_seats WHERE showtime_id=p_showtime ORDER BY seat_id FOR UPDATE;
    PERFORM id FROM app.bookings WHERE showtime_id=p_showtime ORDER BY id FOR UPDATE;
    PERFORM id FROM app.seat_holds WHERE showtime_id=p_showtime ORDER BY id FOR UPDATE;
END $body$;
CREATE FUNCTION app.expire_booking_aggregates(p_showtime bigint) RETURNS integer LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_count integer; v_now timestamptz:=clock_timestamp();
BEGIN
    UPDATE app.bookings SET status='EXPIRED' WHERE showtime_id=p_showtime AND status='PENDING' AND expires_at<=v_now;
    UPDATE app.seat_holds h SET status='EXPIRED' WHERE h.showtime_id=p_showtime AND h.status='ACTIVE'
        AND (h.expires_at<=v_now OR EXISTS(SELECT 1 FROM app.bookings b WHERE b.id=h.booking_id AND b.status='EXPIRED'));
    GET DIAGNOSTICS v_count=ROW_COUNT;
    RETURN v_count;
END $body$;

CREATE FUNCTION app.create_booking(p_showtime bigint,p_user bigint,p_holds bigint[]) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_now timestamptz; v_expiry timestamptz; v_price numeric; v_id bigint; v_existing bigint;
BEGIN
    IF p_holds IS NULL OR cardinality(p_holds)=0 OR EXISTS(SELECT 1 FROM unnest(p_holds) id WHERE id IS NULL OR id<=0)
        OR (SELECT count(DISTINCT id) FROM unnest(p_holds) id)<>cardinality(p_holds) THEN
        RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invalid Hold selection';
    END IF;
    PERFORM app.lock_hold_context(p_showtime,p_user);
    PERFORM app.lock_booking_resources(p_showtime);
    PERFORM app.expire_booking_aggregates(p_showtime);
    v_now:=clock_timestamp();
    SELECT s.base_price,least(s.start_time,s.booking_cut_off) INTO v_price,v_expiry
        FROM app.showtimes s JOIN app.halls h ON h.id=s.hall_id JOIN app.cinemas c ON c.id=h.cinema_id JOIN app.movies m ON m.id=s.movie_id
        WHERE s.id=p_showtime AND s.status='OPEN_FOR_BOOKING' AND s.start_time>v_now AND s.booking_cut_off>v_now
        AND h.status='ACTIVE' AND c.status='ACTIVE' AND m.status='PUBLISHED';
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Showtime unavailable'; END IF;
    IF (SELECT count(*) FROM app.seat_holds h JOIN app.showtime_seats ss ON ss.showtime_id=h.showtime_id AND ss.seat_id=h.seat_id
        JOIN app.seats seat ON seat.id=h.seat_id WHERE h.id=ANY(p_holds) AND h.showtime_id=p_showtime AND h.user_id=p_user
        AND h.status='ACTIVE' AND h.expires_at>v_now AND ss.is_sellable AND seat.physical_status='ACTIVE'
        AND NOT EXISTS(SELECT 1 FROM app.booking_seats bs WHERE bs.showtime_id=p_showtime AND bs.seat_id=h.seat_id AND bs.sold_at IS NOT NULL))<>cardinality(p_holds) THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Hold selection unavailable';
    END IF;
    SELECT min(booking_id) INTO v_existing FROM app.seat_holds WHERE id=ANY(p_holds);
    IF v_existing IS NOT NULL THEN
        IF EXISTS(SELECT 1 FROM app.seat_holds WHERE id=ANY(p_holds) AND booking_id IS DISTINCT FROM v_existing)
            OR (SELECT count(*) FROM app.seat_holds WHERE booking_id=v_existing)<>cardinality(p_holds)
            OR NOT EXISTS(SELECT 1 FROM app.bookings WHERE id=v_existing AND customer_id=p_user AND status='PENDING' AND expires_at>clock_timestamp()) THEN
            RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Hold already attached';
        END IF;
        RETURN v_existing;
    END IF;
    SELECT least(v_expiry,min(expires_at)) INTO v_expiry FROM app.seat_holds WHERE id=ANY(p_holds);
    IF v_price*cardinality(p_holds)>=1000000000000000 THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking amount exceeds supported bounds';
    END IF;
    v_now:=clock_timestamp();
    IF v_expiry<=v_now THEN RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Hold selection expired'; END IF;
    INSERT INTO app.bookings(booking_code,customer_id,showtime_id,seat_amount,concession_amount,subtotal,discount,final_amount,created_at,expires_at)
        VALUES ('B-'||replace(gen_random_uuid()::text,'-',''),p_user,p_showtime,v_price*cardinality(p_holds),0,
            v_price*cardinality(p_holds),0,v_price*cardinality(p_holds),v_now,v_expiry) RETURNING id INTO v_id;
    INSERT INTO app.booking_seats(booking_id,showtime_id,seat_id,seat_type_snapshot,unit_price_snapshot,final_price)
        SELECT v_id,p_showtime,h.seat_id,seat.seat_type,v_price,v_price FROM app.seat_holds h JOIN app.seats seat ON seat.id=h.seat_id
        WHERE h.id=ANY(p_holds) ORDER BY h.seat_id;
    UPDATE app.seat_holds SET booking_id=v_id WHERE id=ANY(p_holds);
    IF v_expiry<=clock_timestamp() THEN RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Hold selection expired'; END IF;
    RETURN v_id;
END $body$;

CREATE FUNCTION app.cancel_booking(p_booking bigint,p_user bigint) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_showtime bigint;
BEGIN
    SELECT showtime_id INTO v_showtime FROM app.bookings WHERE id=p_booking AND customer_id=p_user;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Booking unavailable'; END IF;
    PERFORM app.lock_hold_context(v_showtime,p_user);
    PERFORM app.lock_booking_resources(v_showtime);
    PERFORM app.expire_booking_aggregates(v_showtime);
    UPDATE app.bookings SET status='CANCELLED' WHERE id=p_booking AND customer_id=p_user AND status='PENDING';
    UPDATE app.seat_holds SET status='RELEASED' WHERE booking_id=p_booking AND status='ACTIVE'
        AND EXISTS(SELECT 1 FROM app.bookings WHERE id=p_booking AND status='CANCELLED');
END $body$;
CREATE OR REPLACE FUNCTION app.expire_seat_holds(p_showtime bigint) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
BEGIN
    PERFORM app.lock_hold_context(p_showtime,NULL);
    PERFORM app.lock_booking_resources(p_showtime);
    RETURN app.expire_booking_aggregates(p_showtime);
END $body$;

