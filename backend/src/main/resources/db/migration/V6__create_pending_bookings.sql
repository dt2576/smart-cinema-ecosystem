CREATE FUNCTION app.guard_booking_seat() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
BEGIN
    IF current_user<>'smart_cinema_hold_owner' OR TG_OP<>'INSERT' THEN
        RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Immutable Booking Seat';
    END IF;
    IF NEW.sold_at IS NOT NULL OR NOT EXISTS (
        SELECT 1 FROM app.bookings b JOIN app.showtimes s ON s.id=b.showtime_id
        JOIN app.seat_holds h ON h.showtime_id=b.showtime_id AND h.user_id=b.customer_id AND h.seat_id=NEW.seat_id
        JOIN app.seats seat ON seat.id=h.seat_id
