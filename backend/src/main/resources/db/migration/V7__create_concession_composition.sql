-- Read-only predicate, always used after the gate/rows are locked by a controlled writer.
CREATE FUNCTION app.booking_composition_eligible(p_booking bigint) RETURNS boolean
LANGUAGE sql VOLATILE SET search_path=pg_catalog,pg_temp AS $body$
    SELECT EXISTS(SELECT 1 FROM app.bookings b JOIN app.showtimes s ON s.id=b.showtime_id
        JOIN app.halls h ON h.id=s.hall_id JOIN app.cinemas c ON c.id=h.cinema_id JOIN app.movies m ON m.id=s.movie_id
        JOIN app.users u ON u.id=b.customer_id
        WHERE b.id=p_booking AND b.status='PENDING' AND b.payment_started_at IS NULL AND b.expires_at>clock_timestamp()
        AND s.status='OPEN_FOR_BOOKING' AND s.start_time>clock_timestamp() AND s.booking_cut_off>clock_timestamp()
        AND h.status='ACTIVE' AND c.status='ACTIVE' AND m.status='PUBLISHED' AND u.status='ACTIVE' AND u.role='CUSTOMER'
        AND EXISTS(SELECT 1 FROM app.booking_seats WHERE booking_id=b.id)
        AND NOT EXISTS(SELECT 1 FROM app.booking_seats bs JOIN app.seats seat ON seat.id=bs.seat_id
            JOIN app.showtime_seats ss ON ss.showtime_id=bs.showtime_id AND ss.seat_id=bs.seat_id
            LEFT JOIN app.seat_holds sh ON sh.booking_id=b.id AND sh.seat_id=bs.seat_id
            WHERE bs.booking_id=b.id AND (NOT ss.is_sellable OR seat.physical_status<>'ACTIVE'
                OR sh.id IS NULL OR sh.status<>'ACTIVE' OR sh.expires_at<=clock_timestamp()
                OR sh.user_id<>b.customer_id OR bs.sold_at IS NOT NULL)))
$body$;

CREATE OR REPLACE FUNCTION app.guard_booking() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
BEGIN
    IF current_user<>'smart_cinema_hold_owner' OR TG_OP='DELETE' THEN
        RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Protected Booking mutation';
    END IF;
    IF TG_OP='INSERT' THEN
        IF NEW.status<>'PENDING' OR NEW.expires_at<=clock_timestamp() OR NEW.concession_amount<>0 THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid initial Booking';
        END IF;
    ELSIF NEW.status=OLD.status THEN
        IF (to_jsonb(NEW)-ARRAY['concession_amount','subtotal','final_amount']) IS DISTINCT FROM
            (to_jsonb(OLD)-ARRAY['concession_amount','subtotal','final_amount'])
            OR NOT app.booking_composition_eligible(OLD.id) THEN
            RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking composition unavailable';
        END IF;
    ELSE
        IF (to_jsonb(NEW)-'status') IS DISTINCT FROM (to_jsonb(OLD)-'status')
            OR OLD.status<>'PENDING' OR NEW.status NOT IN ('CANCELLED','EXPIRED')
            OR (NEW.status='EXPIRED' AND NEW.expires_at>clock_timestamp()) THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable Booking history';
        END IF;
    END IF;
    RETURN NEW;
END $body$;

CREATE FUNCTION app.guard_booking_concession() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_booking bigint;
BEGIN
    IF current_user<>'smart_cinema_hold_owner' THEN
        RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Protected Concession mutation';
    END IF;
    v_booking:=CASE WHEN TG_OP='DELETE' THEN OLD.booking_id ELSE NEW.booking_id END;
    IF NOT app.booking_composition_eligible(v_booking) THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking composition unavailable';
    END IF;
    IF TG_OP='INSERT' THEN
        IF NOT EXISTS(SELECT 1 FROM app.concession_items i WHERE i.id=NEW.concession_item_id AND i.status='ACTIVE'
            AND (i.name,i.category,i.selling_price)=(NEW.item_name_snapshot,NEW.category_snapshot,NEW.unit_price_snapshot)) THEN
            RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Concession unavailable';
        END IF;
    ELSIF TG_OP='UPDATE' THEN
        IF (to_jsonb(NEW)-ARRAY['quantity','total_price']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['quantity','total_price']) THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Immutable Concession snapshot';
        END IF;
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $body$;
