CREATE TABLE concession_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_concession_items PRIMARY KEY,
    name varchar(150) NOT NULL,
    description text,
    category varchar(30) NOT NULL,
    selling_price numeric(19,4) NOT NULL,
    image varchar(2048),
    status varchar(20) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamp(6) with time zone NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT chk_concession_items_name CHECK(btrim(name)<>''),
    CONSTRAINT chk_concession_items_description CHECK(description IS NULL OR btrim(description)<>''),
    CONSTRAINT chk_concession_items_image CHECK(image IS NULL OR btrim(image)<>''),
    CONSTRAINT chk_concession_items_category CHECK(category IN ('POPCORN','DRINK','COMBO')),
    CONSTRAINT chk_concession_items_status CHECK(status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT chk_concession_items_price CHECK(selling_price>=0 AND selling_price<1000000000000000),
    CONSTRAINT chk_concession_items_times CHECK(isfinite(created_at) AND isfinite(updated_at) AND updated_at>=created_at)
);
CREATE TABLE booking_concessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_booking_concessions PRIMARY KEY,
    booking_id bigint NOT NULL,
    concession_item_id bigint NOT NULL,
    item_name_snapshot varchar(150) NOT NULL,
    category_snapshot varchar(30) NOT NULL,
    quantity integer NOT NULL,
    unit_price_snapshot numeric(19,4) NOT NULL,
    total_price numeric(19,4) NOT NULL,
    CONSTRAINT fk_booking_concessions_booking FOREIGN KEY(booking_id) REFERENCES bookings(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT fk_booking_concessions_item FOREIGN KEY(concession_item_id) REFERENCES concession_items(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT chk_booking_concessions_name CHECK(btrim(item_name_snapshot)<>''),
    CONSTRAINT chk_booking_concessions_category CHECK(category_snapshot IN ('POPCORN','DRINK','COMBO')),
    CONSTRAINT chk_booking_concessions_quantity CHECK(quantity>0),
    CONSTRAINT chk_booking_concessions_money CHECK(unit_price_snapshot>=0 AND unit_price_snapshot<1000000000000000
        AND total_price>=0 AND total_price<1000000000000000),
    CONSTRAINT chk_booking_concessions_total CHECK(total_price=quantity*unit_price_snapshot)
);
CREATE INDEX idx_booking_concessions_booking ON booking_concessions(booking_id);
CREATE INDEX idx_booking_concessions_item ON booking_concessions(concession_item_id);
CREATE TABLE promotions (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_promotions PRIMARY KEY,
    code varchar(50) NOT NULL CONSTRAINT uq_promotions_code UNIQUE,
    discount_type varchar(20) NOT NULL,
    discount_value numeric(19,4) NOT NULL,
    valid_from timestamp(6) with time zone NOT NULL,
    valid_until timestamp(6) with time zone NOT NULL,
    minimum_order numeric(19,4) NOT NULL,
    usage_limit integer,
    status varchar(20) NOT NULL,
    CONSTRAINT chk_promotions_code CHECK(code=upper(btrim(code)) AND btrim(code)<>''),
    CONSTRAINT chk_promotions_type CHECK(discount_type IN ('FIXED','PERCENTAGE')),
    CONSTRAINT chk_promotions_value CHECK(discount_value>=0 AND discount_value<1000000000000000
        AND (discount_type<>'PERCENTAGE' OR discount_value<=100)),
    CONSTRAINT chk_promotions_window CHECK(isfinite(valid_from) AND isfinite(valid_until) AND valid_until>valid_from),
    CONSTRAINT chk_promotions_minimum CHECK(minimum_order>=0 AND minimum_order<1000000000000000),
    CONSTRAINT chk_promotions_usage CHECK(usage_limit IS NULL OR usage_limit>0),
    CONSTRAINT chk_promotions_status CHECK(status IN ('ACTIVE','INACTIVE'))
);
