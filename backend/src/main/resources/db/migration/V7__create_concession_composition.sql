-- Deployment-only configuration. No Admin HTTP API or seeded product/price is introduced.
CREATE FUNCTION app.configure_concession_item(p_id bigint,p_name text,p_description text,p_category text,p_price numeric,p_image text,p_status text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_id bigint; v_now timestamptz:=clock_timestamp();
BEGIN
    IF p_price IS NULL OR p_price<0 OR p_price>=1000000000000000 OR p_price<>round(p_price,4) THEN
        RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invalid catalog price precision or range';
    END IF;
    IF p_id IS NULL THEN
        INSERT INTO app.concession_items(name,description,category,selling_price,image,status,created_at,updated_at)
            VALUES(p_name,p_description,p_category,p_price,p_image,p_status,v_now,v_now) RETURNING id INTO v_id;
    ELSE
        UPDATE app.concession_items SET name=p_name,description=p_description,category=p_category,selling_price=p_price,image=p_image,status=p_status
            WHERE id=p_id RETURNING id INTO v_id;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Concession unavailable'; END IF;
    END IF;
    RETURN v_id;
END $body$;

CREATE FUNCTION app.edit_booking_concession(p_booking bigint,p_user bigint,p_line bigint,p_item bigint,p_quantity integer,p_operation text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE v_showtime bigint; v_item app.concession_items%ROWTYPE; v_line app.booking_concessions%ROWTYPE;
    v_price numeric; v_line_total numeric; v_total numeric; v_seat_amount numeric;
BEGIN
    IF p_operation IS NULL OR p_operation NOT IN ('ADD','UPDATE','REMOVE')
        OR (p_operation IN ('ADD','UPDATE') AND (p_quantity IS NULL OR p_quantity<=0))
        OR (p_operation='ADD' AND (p_item IS NULL OR p_item<=0 OR p_line IS NOT NULL))
        OR (p_operation<>'ADD' AND (p_line IS NULL OR p_line<=0 OR p_item IS NOT NULL)) THEN
        RAISE EXCEPTION USING ERRCODE='P0001',MESSAGE='Invalid Concession command';
    END IF;
    SELECT showtime_id INTO v_showtime FROM app.bookings WHERE id=p_booking AND customer_id=p_user;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Booking unavailable'; END IF;
    PERFORM app.lock_hold_context(v_showtime,p_user);
    PERFORM app.lock_booking_resources(v_showtime);
    PERFORM app.expire_booking_aggregates(v_showtime);
    IF NOT app.booking_composition_eligible(p_booking) THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking composition unavailable';
    END IF;
    IF p_operation='ADD' THEN
        SELECT * INTO v_item FROM app.concession_items WHERE id=p_item AND status='ACTIVE' FOR SHARE;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Concession unavailable'; END IF;
        v_price:=v_item.selling_price;
    ELSE
        SELECT * INTO v_line FROM app.booking_concessions WHERE id=p_line AND booking_id=p_booking FOR UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Concession line unavailable'; END IF;
        v_price:=v_line.unit_price_snapshot;
    END IF;
    v_line_total:=CASE WHEN p_operation='REMOVE' THEN 0 ELSE v_price*p_quantity END;
    SELECT coalesce(sum(total_price),0) INTO v_total FROM app.booking_concessions WHERE booking_id=p_booking;
    v_total:=v_total-coalesce(v_line.total_price,0)+v_line_total;
    SELECT seat_amount INTO v_seat_amount FROM app.bookings WHERE id=p_booking;
    IF v_line_total>=1000000000000000 OR v_total>=1000000000000000 OR v_total+v_seat_amount>=1000000000000000 THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking amount exceeds supported bounds';
    END IF;
    IF p_operation='ADD' THEN
        INSERT INTO app.booking_concessions(booking_id,concession_item_id,item_name_snapshot,category_snapshot,quantity,unit_price_snapshot,total_price)
            VALUES(p_booking,p_item,v_item.name,v_item.category,p_quantity,v_price,v_line_total);
    ELSIF p_operation='UPDATE' THEN
        UPDATE app.booking_concessions SET quantity=p_quantity,total_price=v_line_total WHERE id=p_line;
    ELSE
        DELETE FROM app.booking_concessions WHERE id=p_line;
    END IF;
    UPDATE app.bookings SET concession_amount=v_total,subtotal=seat_amount+v_total,final_amount=seat_amount+v_total WHERE id=p_booking;
    IF NOT app.booking_composition_eligible(p_booking) THEN
        RAISE EXCEPTION USING ERRCODE='P0003',MESSAGE='Booking composition expired';
    END IF;
END $body$;

