CREATE FUNCTION app.guard_seat_hold() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $body$
BEGIN
    IF current_user <> 'smart_cinema_hold_owner' OR TG_OP='DELETE' THEN
        RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Protected Hold mutation';
    END IF;
    IF TG_OP='UPDATE' THEN
        IF (NEW.id,NEW.showtime_id,NEW.seat_id,NEW.user_id,NEW.booking_id,NEW.created_at,NEW.expires_at)
            IS DISTINCT FROM (OLD.id,OLD.showtime_id,OLD.seat_id,OLD.user_id,OLD.booking_id,OLD.created_at,OLD.expires_at)
            OR OLD.status <> 'ACTIVE' OR NEW.status NOT IN ('EXPIRED','RELEASED') THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Immutable Hold history';
        END IF;
        IF NEW.status='EXPIRED' AND OLD.expires_at > clock_timestamp() THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Hold is not expired';
        END IF;
    ELSE
        IF NEW.status <> 'ACTIVE' OR NEW.booking_id IS NOT NULL
            OR NEW.expires_at <= clock_timestamp() OR NOT EXISTS (
                SELECT 1 FROM app.showtime_seats ss JOIN app.seats seat ON seat.id=ss.seat_id
                JOIN app.showtimes s ON s.id=ss.showtime_id JOIN app.halls h ON h.id=s.hall_id
                JOIN app.cinemas c ON c.id=h.cinema_id JOIN app.movies m ON m.id=s.movie_id
                JOIN app.users u ON u.id=NEW.user_id
                WHERE ss.showtime_id=NEW.showtime_id AND ss.seat_id=NEW.seat_id AND ss.is_sellable
                AND seat.physical_status='ACTIVE' AND u.role='CUSTOMER' AND u.status='ACTIVE'
                AND m.status='PUBLISHED' AND c.status='ACTIVE' AND h.status='ACTIVE'
                AND s.status='OPEN_FOR_BOOKING' AND s.start_time > clock_timestamp()
                AND s.booking_cut_off > clock_timestamp() AND NEW.expires_at <= s.booking_cut_off) THEN
            RAISE EXCEPTION USING ERRCODE='P0003', MESSAGE='Seat selection unavailable';
        END IF;
    END IF;
    RETURN NEW;
END $body$;

